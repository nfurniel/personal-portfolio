// Generates SVG path data for the preloader name from a font file.
//
//   node scripts/generate-name-paths.mjs preview <out.html> <font1.ttf> [font2.ttf ...]
//   node scripts/generate-name-paths.mjs bake <font.ttf> <out.js> [letterSpacingEm]
//
// The baked module is imported by NamePreloader.jsx, so the font itself is
// never shipped — only its outlines for the name below.
import { writeFileSync } from 'node:fs'
import { basename } from 'node:path'
import * as fontkit from 'fontkit'

const NAME = process.env.NAME_TEXT || 'Nicolás Furnieles'
const FONT_SIZE = 100

function glyphToPathData(glyph, scale, dx) {
  let d = ''
  const tx = (x) => +(x * scale + dx).toFixed(2)
  const ty = (y) => +(-y * scale).toFixed(2)
  for (const { command, args } of glyph.path.commands) {
    switch (command) {
      case 'moveTo':
        d += `M${tx(args[0])} ${ty(args[1])}`
        break
      case 'lineTo':
        d += `L${tx(args[0])} ${ty(args[1])}`
        break
      case 'quadraticCurveTo':
        d += `Q${tx(args[0])} ${ty(args[1])} ${tx(args[2])} ${ty(args[3])}`
        break
      case 'bezierCurveTo':
        d += `C${tx(args[0])} ${ty(args[1])} ${tx(args[2])} ${ty(args[3])} ${tx(args[4])} ${ty(args[5])}`
        break
      case 'closePath':
        d += 'Z'
        break
    }
  }
  return d
}

function extract(fontPath, letterSpacingEm = 0) {
  const font = fontkit.openSync(fontPath)
  const scale = FONT_SIZE / font.unitsPerEm
  const run = font.layout(NAME)
  const tracking = letterSpacingEm * FONT_SIZE

  const glyphs = []
  let x = 0
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity

  run.glyphs.forEach((glyph, i) => {
    const pos = run.positions[i]
    const dx = x + pos.xOffset * scale
    const d = glyphToPathData(glyph, scale, dx)
    x += pos.xAdvance * scale + tracking
    if (!d) return

    const bb = glyph.bbox
    const x1 = bb.minX * scale + dx
    const x2 = bb.maxX * scale + dx
    const y1 = -bb.maxY * scale
    const y2 = -bb.minY * scale
    glyphs.push({ d, cx: +((x1 + x2) / 2).toFixed(2) })
    minX = Math.min(minX, x1)
    minY = Math.min(minY, y1)
    maxX = Math.max(maxX, x2)
    maxY = Math.max(maxY, y2)
  })

  const pad = 8
  return {
    glyphs,
    viewBox: `${(minX - pad).toFixed(1)} ${(minY - pad).toFixed(1)} ${(maxX - minX + pad * 2).toFixed(1)} ${(maxY - minY + pad * 2).toFixed(1)}`,
    centerX: +((minX + maxX) / 2).toFixed(2),
  }
}

const [, , mode, ...args] = process.argv

if (mode === 'preview') {
  const [out, ...fonts] = args
  const sections = fonts.map((f) => {
    const { glyphs, viewBox } = extract(f)
    return `<section><h2>${basename(f)}</h2><svg viewBox="${viewBox}">${glyphs
      .map((g) => `<path d="${g.d}"/>`)
      .join('')}</svg></section>`
  })
  writeFileSync(
    out,
    `<!doctype html><html><head><meta charset="utf-8"><title>font preview</title><style>
      body{background:#0a0a0a;margin:0;padding:4vh 5vw;display:flex;flex-direction:column;gap:5vh}
      h2{color:#666;font:14px monospace;margin:0 0 8px}
      svg{width:100%;height:auto;overflow:visible;display:block}
      path{fill:#f5f5f5;stroke:#f5f5f5;stroke-width:.8}
    </style></head><body>${sections.join('')}</body></html>`,
  )
  console.log(`preview written: ${out}`)
} else if (mode === 'bake') {
  const [fontPath, out, ls = '0'] = args
  const { glyphs, viewBox, centerX } = extract(fontPath, parseFloat(ls))
  writeFileSync(
    out,
    `// Auto-generated by scripts/generate-name-paths.mjs from ${basename(fontPath)}
// Text: "${NAME}" — do not edit by hand, re-run the script instead.
export const NAME_VIEWBOX = '${viewBox}'
export const NAME_CENTER_X = ${centerX}
export const NAME_GLYPHS = ${JSON.stringify(glyphs, null, 2)}
`,
  )
  console.log(`baked ${glyphs.length} glyphs -> ${out}`)
} else {
  console.error('usage: preview <out.html> <fonts...> | bake <font> <out.js> [letterSpacingEm]')
  process.exit(1)
}
