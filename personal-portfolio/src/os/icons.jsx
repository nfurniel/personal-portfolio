function toPath(rows) {
  let d = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') d += `M${x} ${y}h1v1h-1z`
    }
  })
  return d
}

const PATHS = Object.fromEntries(
  Object.entries(ICONS).map(([k, rows]) => [k, { d: toPath(rows), w: rows[0].length, h: rows.length }]),
)

export function ProjectIcon({ kind, className = '' }) {
  const icon = PATHS[kind]
  return (
    <svg
      className={`px-icon ${className}`}
      viewBox={`-1 -1 ${icon.w + 2} ${icon.h + 2}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={icon.d} fill="currentColor" />
    </svg>
  )
}

// Generic name for the same component: every pixel icon, not only projects.
export const PixelIcon = ProjectIcon
